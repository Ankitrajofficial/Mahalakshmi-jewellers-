type StoneDraft = {
  type: string
  shape?: string
  count: number
  carat: number
  clarity?: string
  colour?: string
  cert?: string
  rate: number
}

type Draft = {
  slug: string
  name: string
  category: string
  sku: string
  short: string
  description: string
  craft: string
  care: string
  metal: Metal
  purity: Purity
  colour?: MetalColour
  gross: number
  net: number
  mode?: PricingMode
  makingType?: MakingType
  making?: number
  wastage?: number
  fixed?: number
  stones?: StoneDraft[]
  huid?: string
  cert?: string
  sizes?: string[]
  dims?: string
  tags: string[]
  stock?: number
  mto?: boolean
  lead?: number
  featured?: boolean
  /** SVG motif + metal tone used to render this product's plates. */
  motif: string
  tone: string
  video?: string
  created: string
}

function build(d: Draft, index: number): Product {
  const category = CATEGORY_BY_SLUG.get(d.category)
  if (!category) throw new Error(`Unknown category slug: ${d.category}`)

  const stones: Stone[] = (d.stones ?? []).map((s, i) => ({
    id: `${d.slug}-stone-${i + 1}`,
    type: s.type,
    shape: s.shape ?? null,
    count: s.count,
    carat: s.carat,
    clarity: s.clarity ?? null,
    colour: s.colour ?? null,
    certification: s.cert ?? null,
    ratePerCarat: s.rate,
  }))

  // A real photograph replaces the whole plate set: mixing one photo with two
  // illustrated plates in a gallery reads as a mistake. Products without a
  // photo keep the SVG plates.
  const photo = PRODUCT_PHOTOS[d.slug]
  const images: Product['images'] = photo
    ? [
        {
          id: `${d.slug}-img-1`,
          url: photo.url,
          alt: photo.alt,
          kind: 'product',
          width: photo.width,
          height: photo.height,
          blurDataURL: photo.blurDataURL,
          position: 0,
        },
      ]
    : [
        {
          id: `${d.slug}-img-1`,
          url: `/catalog/${d.slug}-1.svg`,
          alt: `${d.name} — ${d.purity} ${d.metal.toLowerCase()}, front view`,
          kind: 'product',
          width: 1600,
          height: 1600,
          blurDataURL: BLUR,
          position: 0,
        },
        {
          id: `${d.slug}-img-2`,
          url: `/catalog/${d.slug}-2.svg`,
          alt: `${d.name} styled on a Jaipur editorial set`,
          kind: 'lifestyle',
          width: 1600,
          height: 1600,
          blurDataURL: BLUR,
          position: 1,
        },
        {
          id: `${d.slug}-img-3`,
          url: `/catalog/${d.slug}-3.svg`,
          alt: `${d.name} shown against a 20 mm coin and centimetre scale`,
          kind: 'scale',
          width: 1600,
          height: 1600,
          blurDataURL: BLUR,
          position: 2,
        },
      ]
  if (d.cert) {
    images.push({
      id: `${d.slug}-img-cert`,
      url: `/catalog/${d.slug}-cert.svg`,
      alt: `${d.cert} certificate supplied with ${d.name}`,
      kind: 'certificate',
      width: 1600,
      height: 1600,
      blurDataURL: BLUR,
      position: images.length,
    })
  }

  return {
    id: `prd-${String(index + 1).padStart(3, '0')}`,
    slug: d.slug,
    name: d.name,
    shortDescription: d.short,
    description: d.description,
    craftsmanship: d.craft,
    careNotes: d.care,
    categoryId: category.id,
    categorySlug: category.slug,
    categoryName: category.name,
    collectionTags: d.tags,
    metal: d.metal,
    purity: d.purity,
    metalColour: d.colour ?? null,
    grossWeightG: d.gross,
    netMetalWeightG: d.net,
    stones,
    pricingMode: d.mode ?? 'DYNAMIC_BY_WEIGHT',
    makingChargeType: d.makingType ?? 'PER_GRAM',
    makingChargeValue: d.making ?? 0,
    wastagePercent: d.wastage ?? null,
    fixedPrice: d.fixed ?? null,
    bisHallmarked: d.metal !== 'SILVER' ? true : true,
    huid: d.huid ?? null,
    certification: d.cert ?? null,
    sku: d.sku,
    stockQty: d.stock ?? 1,
    isMadeToOrder: d.mto ?? false,
    leadTimeDays: d.lead ?? null,
    sizeOptions: d.sizes ?? [],
    dimensions: d.dims ?? null,
    images,
    video: d.video ?? null,
    isActive: true,
    isFeatured: d.featured ?? false,
    metaTitle: `${d.name} | ${d.purity} ${titleCase(d.metal)} | Mahalaxmi Jewellers Jaipur`,
    metaDescription: `${d.short} BIS hallmarked, online payment only, insured delivery across India from our Panch Batti showroom in Jaipur.`,
    createdAt: d.created,
    updatedAt: d.created,
  }
}

function titleCase(s: string): string {
  return s.charAt(0) + s.slice(1).toLowerCase()
}

